def main():
    langs = {code: name for code, name in LANGS}
    catalogues = {
        code: json.loads((ROOT / "data/i18n" / f"{code}.json").read_text())
        for code in langs if code != "it"
    }
    out = {}
    for code in langs:
        texts = T[code]
        assert len(texts) == len(IDS), (code, len(texts))
        entry = dict(zip(IDS, texts))
        for key, it in FROM_GAME.items():
            entry[key] = it if code == "it" else catalogues[code].get(it, it)
        out[code] = entry
    missing = sorted(set(langs) - set(T))
    assert not missing, missing
    body = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
    names = json.dumps(LANGS, ensure_ascii=False, separators=(",", ":"))
    (ROOT / "web/i18n.js").write_text(
        "// Generated by tools/i18n/landing.py: do not edit.\n"
        f"window.ROCCA_LANGS={names};\nwindow.ROCCA_TEXTS={body};\n"
    )


